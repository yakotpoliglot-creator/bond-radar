/* 'ref' — справочное значение: серый, без оценки. */
export const TONE_LABEL = {
  good: 'в норме', warn: 'внимание', bad: 'риск', na: 'нет данных', ref: 'справочно',
};
export const TONE_CLS = { good: 'c-g', warn: 'c-a', bad: 'c-r', na: 'c-3', ref: 'c-3' };

/** Значение метрики за самый свежий год, где оно есть. */
export function latest(metric) {
  if (!metric?.values) return null;
  const years = Object.keys(metric.values).sort();
  const y = years[years.length - 1];
  return y ? { year: y, value: metric.values[y] } : null;
}

/* ── Отсечка абсурдных значений ──────────────────────────────────────
   Коэффициент с околонулевым или отрицательным знаменателем — мусор, а не
   «очень плохо»: у SPV и у убыточных компаний долг/EBITDA обращается в
   166×, ROE — в тысячи процентов. Оригинал в таких случаях печатает
   «н/д» (BR-062), мы делаем так же и говорим в подсказке, почему.
   Предел задаёт сама метрика полем maxAbs; у оценок «дорого/дёшево» его
   нет — большое P/E это дорогая компания, а не ошибка счёта. */
export function ratioValue(r, v) {
  if (v == null || Number.isNaN(v)) return { na: true, why: 'нет данных' };
  if (r.maxAbs != null && Math.abs(v) > r.maxAbs) {
    return {
      na: true, sanitized: true,
      why: r.unit === '×'
        ? 'Коэффициент неинформативен: знаменатель близок к нулю или отрицателен'
        : 'Знаменатель близок к нулю — показатель неинформативен',
    };
  }
  return { na: false, value: v, tone: r.ref ? 'ref' : r.tone(v) };
}

/* Число для плитки — как у оригинала: «1,3×» и «39 %», а не «1,30×» и
   «39,0 %». Множители до одного знака, проценты — целыми. */
export function ratioText(r, v) {
  return r.unit === '%' ? nf(Math.round(v), 0) : nf(v, 1);
}

/* ── Метрики для карточки предприятия ────────────────────────────────
   Тот же светофор и те же пороги, что в панели коэффициентов, но набор
   как в карточке у оригинала: сначала кредитные (цветные), потом
   справочные (серые). Нужны там, где таблице места нет: на карточке
   выпуска, на странице эмитента в окне и в быстром просмотре из списка
   (components/IssuerCard). Считает по-прежнему этот файл, чтобы «норма»
   на карточке и в панели коэффициентов не разошлась.
   Текущей ликвидности в наборе нет не по забывчивости: в источнике
   (smart-lab.ru) её нет ни у одного эмитента. */
export const CARD_RATIO_KEYS = [
  'debtEbitda', 'netDebtEbitda', 'interestCoverage',
  'ebitdaMargin', 'netMargin', 'roe',
];

export function ratioStats(fin, keys = CARD_RATIO_KEYS) {
  const m = fin?.metrics;
  if (!m) return [];
  return keys.map(k => {
    const r = RATIOS.find(x => x.key === k);
    if (!r) return null;
    const l = latest(m[k]);
    if (!l) return null;
    const v = ratioValue(r, l.value);
    const tone = v.na ? 'na' : v.tone;
    return {
      key: k, label: r.label, unit: r.unit, year: l.year,
      value: l.value,
      text: v.na ? 'н/д' : ratioText(r, l.value),
      tone,
      toneLabel: v.na ? (v.sanitized ? 'неинформативно' : TONE_LABEL.na) : TONE_LABEL[tone],
      hint: v.na ? v.why : r.hint,
      na: !!v.na,
    };
  }).filter(Boolean);
}

/* Свежий отчётный период одной строкой — как «Отчётность МСФО 2026 ·
   1 полугодие · выручка 1880,0 млрд ₽ · чистая прибыль 286,1 млрд ₽»
   в карточке у оригинала. Годовая таблица отвечает «как менялось»,
   эта строка — «что показали в последнем отчёте», и на карточке
   выпуска хватает её одной. */
export function latestPeriodLine(q) {
  const p = q?.periods?.[q.periods.length - 1];
  if (!p) return null;
  const val = k => q?.metrics?.[k]?.values?.[p.label] ?? null;
  const parts = [];
  for (const [k, label] of [['revenue', 'выручка'], ['ebitda', 'EBITDA'], ['netProfit', 'чистая прибыль']]) {
    const v = val(k);
    if (v != null) parts.push(`${label} ${nf(v, 1)} млрд ₽`);
  }
  if (!parts.length) return null;
  return { label: p.label, date: p.date, text: parts.join(' · ') };
}
