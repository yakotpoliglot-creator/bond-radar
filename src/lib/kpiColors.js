/* ═══════════════════════════════════════════════════════════════════
   Палитра плиток выпуска — как у оригинала.

   Цвет плитки здесь — не оценка «хорошо/плохо», а подсказка, о чём цифра:
   купон зелёный, доходность синяя, дюрация фиолетовая, цена ниже 90 %
   номинала красная, оферта янтарная, номинал и сроки — обычным текстом.
   Флоатер всюду янтарный: ставка его купонов вперёд неизвестна, и зелёный
   цвет обещал бы то, чего эмитент не обещал.

   Токены те же, что у оригинала (--blue #1d4ed8 / #7aa2f7, --purple
   #7c3aed / #b699f7), поэтому светлая и тёмная темы совпадают с ним.

   Не путать со светофором из lib/ratios: там цвет значит «норма / внимание /
   риск» и отвечает на вопрос «насколько это опасно», а здесь — «о чём эта
   цифра». Одна и та же цифра может быть синей в плитке и красной в светофоре,
   и это не противоречие: вопросы разные.
   ═══════════════════════════════════════════════════════════════════ */

/** Цена: ниже 90 % номинала — красная (глубокий дисконт), иначе текст. */
export const priceColor = p => (p == null ? 'var(--text3)' : p < 90 ? 'var(--red)' : 'var(--text)');

/** Доходность: флоатеру — янтарный (число примерное), фиксу — синий. */
export const ytmColor = isFloater => (isFloater ? 'var(--amber)' : 'var(--blue)');

/** Купон: у флоатера это ставка текущего периода, а не обещание на весь срок.
    У фикса зелёный, но с 19 % — янтарный: это уже высокодоходная бумага, и
    ровный зелёный читался бы как «всё хорошо». */
export const couponColor = (isFloater, couponPercent) => (
  isFloater || (couponPercent != null && couponPercent >= 19) ? 'var(--amber)' : 'var(--green)'
);

/** Цвета полей без порогов: у них цвет один всегда. muted — прочерк. */
export const KPI_COLOR = {
  couponToPrice: 'var(--green)',
  duration: 'var(--purple)',
  offer: 'var(--amber)',
  face: 'var(--text)',
  payments: 'var(--text)',
  maturity: 'var(--text)',
  muted: 'var(--text3)',
};
