#!/usr/bin/env bash
# Коммит и пуш данных, которые собрал робот.
#
# Зовут так:
#   bash scripts/commit-robot-data.sh "первичные размещения $(date -u +%Y-%m-%d)" \
#     public/placements.json .github/last-robot-run.txt
# Первый аргумент — то, что подставится в сообщение коммита после «Робот: ».
# Остальные — файлы, которые робот мог изменить.
#
# Почему один скрипт на всех. До этого в каждом воркфлоу лежала своя копия
# одного и того же цикла, и во всех шести была одна и та же ошибка. Чинить
# её шесть раз — значит однажды починить в пяти местах.
#
# ── Зачем вообще цикл ─────────────────────────────────────────────
# Робот собирает данные 2–40 минут, и всё это время ветка живёт своей
# жизнью: пять других роботов и человек пушат в master параллельно. Git
# отвергает пуш целиком, если ветка ушла вперёд, — и тогда данные всего
# прогона теряются, а прогон краснеет. Поэтому пуш повторяем, перенося
# свой коммит поверх того, что уже лежит в ветке.
#
# ── Что было не так в прежнем цикле ───────────────────────────────
# GitHub запускает run: как `bash -e {0}`, то есть любая неуспешная
# команда вне условий обрывает шаг. В прежнем цикле после неудачного
# пуша стояло
#
#     git pull --rebase --autostash || git rebase --abort
#
# и если pull не смог даже связаться с сервером (сеть, 5xx, лимит), то
# rebase не начинался, `git rebase --abort` падал с «fatal: no rebase in
# progress» — и шаг умирал на ПЕРВОЙ попытке: попытки 2 и 3 не делались
# вовсе, а в аннотации GitHub оставалось только «Process completed with
# exit code 1». Воспроизведено 07.11.2026 на копии шага: код возврата 128.
#
# Второй случай — конфликт в самом файле данных. JSON построчно не
# сливается: если тот же public/*.json успел измениться в ветке, pull
# встаёт на конфликте, `git rebase --abort` его отменяет, и цикл трижды
# повторяет заведомо провальный пуш. Итог — «Не удалось запушить за три
# попытки» и exit code 1, то есть ровно то, что видно в аннотации упавшего
# прогона «Первичные размещения» #244 от 04.11.2026. Данные при этом
# собраны и лежат в раннере, но в ветку не попадают.
#
# ── Что здесь сделано иначе ───────────────────────────────────────
# 1. `git rebase --abort` больше не может уронить шаг: он вызывается
#    только когда rebase действительно идёт.
# 2. Конфликт в сгенерированных данных разрешается, а не отменяется:
#    остаётся свежая версия робота. Свой файл собран минуту назад и
#    покрывает то же окно, что и версия в ветке, поэтому терять нечего,
#    а сливать построчно JSON нечего в принципе.
# 3. Попыток пять, пауза растёт: короткая ошибка GitHub успевает пройти.
# 4. Причина отказа видна в логе: git печатает свою ошибку целиком, а не
#    только «exit code 1».
#
# ── Чего скрипт не делает ─────────────────────────────────────────
# Он не собирает данные и не проверяет их содержимое: это дело робота.
# Если сбор упал, файл не меняется, `git diff --staged` пуст, скрипт
# молча выходит с нулём — красный прогон будет у шага сбора, где и
# должна быть видна причина.

set -u

label="${1:-}"
if [ -z "$label" ]; then
  echo "Зовут так: bash scripts/commit-robot-data.sh \"название робота\" <файлы...>" >&2
  exit 2
fi
shift

if [ "$#" -eq 0 ]; then
  echo "Не передано ни одного файла данных — коммитить нечего." >&2
  exit 2
fi

# Ветка, в которую пушит робот. В Actions это обычно master; берём из
# окружения, чтобы скрипт не зависел от того, настроен ли upstream у
# локальной ветки (у checkout@v4 он есть, но полагаться на это незачем).
branch="${GITHUB_REF_NAME:-master}"

git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"

# Файла может не быть вовсе — это не ошибка: робот мог не создать его в
# первом прогоне. Такой путь просто пропускаем.
for f in "$@"; do
  if [ -e "$f" ]; then
    git add -- "$f"
  else
    echo "Файла $f нет — пропускаю."
  fi
done

if git diff --staged --quiet; then
  echo "Изменений нет — коммит не нужен."
  exit 0
fi

git commit -m "Робот: $label"

attempt=1
max_attempts=5
while [ "$attempt" -le "$max_attempts" ]; do
  if git push origin "HEAD:$branch"; then
    echo "Запушено с попытки $attempt из $max_attempts."
    exit 0
  fi

  echo "Пуш не прошёл (попытка $attempt из $max_attempts) — смотрю, что нового в ветке."

  # Забираем то, что успело лечь в ветку, и переносим наш коммит поверх.
  if ! git pull --rebase --autostash origin "$branch"; then
    gitdir="$(git rev-parse --git-dir)"
    if [ -d "$gitdir/rebase-merge" ] || [ -d "$gitdir/rebase-apply" ]; then
      # Конфликт. Он возможен только в сгенерированных данных: строки JSON
      # не сливаются. В rebase «theirs» — это наш коммит, «ours» — ветка,
      # поверх которой мы его переносим, поэтому свежую версию робота
      # берём через --theirs.
      echo "Конфликт в данных — оставляю свежую версию робота."
      git checkout --theirs -- "$@" 2>/dev/null || true
      for f in "$@"; do
        [ -e "$f" ] && git add -- "$f"
      done
      # --continue открывает редактор для сообщения коммита: в CI редактора
      # нет, поэтому подставляем true.
      if ! GIT_EDITOR=true git rebase --continue; then
        echo "Перенести свой коммит поверх ветки не удалось."
        git rebase --abort || true
      fi
    else
      # Конфликта нет: до сервера не достучались или он ответил ошибкой.
      # Наш коммит на месте, надо просто подождать и попробовать снова.
      echo "Ветку забрать не удалось — это не конфликт, повторяю позже."
    fi
  fi

  sleep $((attempt * 10))
  attempt=$((attempt + 1))
done

echo "Не удалось запушить за $max_attempts попыток. Причина — в выводе git push выше." >&2
exit 1
